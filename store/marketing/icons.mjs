// Extracts the Phosphor icons used by the store graphics into icons.js, so the
// templates draw the same icons as the app instead of emoji.
//
//   node store/marketing/icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const defs = path.join(here, '../../node_modules/phosphor-react-native/src/defs');

const NAMES = [
  'Avocado', 'BowlFood', 'Bread', 'CalendarCheck', 'Carrot', 'ChartLineDown', 'CheckCircle',
  'Cheese', 'Cherries', 'Egg', 'Fire', 'Fish', 'Flower', 'ForkKnife', 'Leaf', 'Moon', 'Orange',
  'OrangeSlice', 'Pepper', 'Plant', 'Scales', 'ShoppingCart', 'Sparkle', 'TrendDown',
];

const icons = {};
for (const name of NAMES) {
  const src = fs.readFileSync(path.join(defs, `${name}.tsx`), 'utf8');
  // The `fill` weight: solid shapes read best at sticker size.
  const block = src.slice(src.indexOf("'fill'"), src.indexOf("'light'"));
  icons[name] = [...block.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
}
fs.writeFileSync(
  path.join(here, 'icons.js'),
  `// Generated by icons.mjs from phosphor-react-native: do not edit.\n` +
    `window.ICONS = ${JSON.stringify(icons)};\n` +
    `window.icon = (name, color, size = '1em') => \`<svg viewBox="0 0 256 256" width="\${size}" height="\${size}" fill="\${color}">\${window.ICONS[name].map((d) => \`<path d="\${d}"/>\`).join('')}</svg>\`;\n`,
);
console.log(`✓ ${NAMES.length} icone`);
